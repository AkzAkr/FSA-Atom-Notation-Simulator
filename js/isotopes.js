function getKnownIsotopeMassRange(symbol) {
  return ISOTOPE_MASS_RANGES[symbol] || null;
}

function isKnownIsotopeMass(symbol, massNum) {
  const range = getKnownIsotopeMassRange(symbol);
  return !!range && massNum >= range[0] && massNum <= range[1];
}
